#!/bin/sh
# Regenerate src/trust_anchors.h from the PEM files in certs/.
# Requires the brssl tool built from vendor/BearSSL (make bearssl-tools).
set -eu
cd "$(dirname "$0")/.."
BRSSL=build/bearssl/brssl
[ -x "$BRSSL" ] || { echo "build $BRSSL first: make bearssl-tools" >&2; exit 1; }
{
  echo "/* Generated by tools/gen-trust-anchors.sh from the PEM files in certs/. Do not edit. */"
  "$BRSSL" ta -q certs/*.pem
} > src/trust_anchors.h
echo "wrote src/trust_anchors.h"
